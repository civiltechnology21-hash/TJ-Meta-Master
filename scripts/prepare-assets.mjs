// Runs automatically before `npm run dev` and `npm run build` (see package.json).
//  1) copies the Ghostscript WebAssembly files into public/gs  (EPS rendering)
//  2) finds your logo / name image in public/ and writes src/lib/brand.generated.ts
//
// To change the logo: put  public/logo.(png|jpg|jpeg|webp|svg)  and optionally
// public/brand-name.(png|jpg|jpeg|webp|svg)  and redeploy. No code changes needed.
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");

/* ---------------------------- 1) Ghostscript ----------------------------- */
const gsFrom = join(root, "node_modules", "@bentopdf", "gs-wasm", "assets");
const gsTo = join(pub, "gs");
mkdirSync(gsTo, { recursive: true });
for (const file of ["gs.js", "gs.wasm"]) {
  const from = join(gsFrom, file);
  if (existsSync(from)) copyFileSync(from, join(gsTo, file));
  else console.warn(`[assets] ${from} not found - run "npm install" (EPS rendering needs it).`);
}

/* ------------------------------- 2) Brand -------------------------------- */
const FORMATS = [
  ["png", "image/png"],
  ["jpg", "image/jpeg"],
  ["jpeg", "image/jpeg"],
  ["webp", "image/webp"],
  ["svg", "image/svg+xml"],
];

function find(baseName) {
  for (const [ext, type] of FORMATS) {
    const path = join(pub, `${baseName}.${ext}`);
    if (existsSync(path)) {
      const hash = createHash("sha1").update(readFileSync(path)).digest("hex").slice(0, 8);
      return { url: `/${baseName}.${ext}?v=${hash}`, type };
    }
  }
  return null;
}

const logo = find("logo");
const name = find("brand-name");
// Optional: a version of the name picture for the light theme (dark lettering).
const nameLight = find("brand-name-light");
if (!logo) console.warn("[assets] No public/logo.(png|jpg|jpeg|webp|svg) found.");

const out = `// AUTO-GENERATED by scripts/prepare-assets.mjs - do not edit by hand.
export const BRAND: { logo: string; logoType: string; name: string | null; nameLight: string | null } = {
  logo: ${JSON.stringify(logo?.url ?? "/logo.png")},
  logoType: ${JSON.stringify(logo?.type ?? "image/png")},
  name: ${JSON.stringify(name?.url ?? null)},
  nameLight: ${JSON.stringify(nameLight?.url ?? null)},
};
`;
writeFileSync(join(root, "src", "lib", "brand.generated.ts"), out);
console.log(`[assets] logo: ${logo?.url ?? "none"} | name image: ${name?.url ?? "none (text is used)"} | light name image: ${nameLight?.url ?? "none"}`);
